/**
 * Builds the MCP App UIs (shown inside AI chats) into single self-contained HTML files —
 * chats render an app from one HTML document, they can't load the site's pages or assets.
 *
 * Output: src/lib/mcp-apps/<name>.html.ts (generated, gitignored), imported by src/lib/mcp.ts.
 * Runs before `next dev` / `next build` (see package.json).
 */
import { mkdir, writeFile } from "node:fs/promises";
import { $ } from "bun";

const APPS = ["image-picker"];
const OUT_DIR = "src/lib/mcp-apps";

await mkdir(OUT_DIR, { recursive: true });

for (const name of APPS) {
  const dir = `src/mcp-apps/${name}`;

  const build = await Bun.build({
    entrypoints: [`${dir}/main.tsx`],
    target: "browser",
    minify: true,
    define: { "process.env.NODE_ENV": '"production"' },
  });
  if (!build.success) throw new AggregateError(build.logs, `MCP app "${name}" failed to build`);
  const js = (await build.outputs[0].text()).replaceAll("</script", "<\\/script");

  const css = await $`bunx @tailwindcss/cli -i ${dir}/styles.css --minify`.quiet().text();

  const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><style>${css}</style></head><body><div id="root"></div><script type="module">${js}</script></body></html>`;

  await writeFile(`${OUT_DIR}/${name}.html.ts`, `// Generated by scripts/build-mcp-apps.ts — do not edit.\nexport default ${JSON.stringify(html)};\n`);
  console.log(`MCP app "${name}": ${(html.length / 1024).toFixed(0)} KB`);
}
